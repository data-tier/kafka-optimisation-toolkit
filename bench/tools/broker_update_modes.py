#!/usr/bin/env python3
"""Regenerate bench/broker-update-modes.tsv from the Kafka broker config reference.

bench/sweep.sh reads that file to decide how to apply a broker-side setting:
cluster-wide and per-broker settings are applied with kafka-configs.sh --alter,
read-only settings by restarting the brokers with the setting in
server.properties. The file is checked in so a sweep never depends on the
network, and this script records where it came from.

Usage: bench/tools/broker_update_modes.py [URL] > bench/broker-update-modes.tsv
"""
import datetime
import html
import re
import sys
import urllib.request

URL = sys.argv[1] if len(sys.argv) > 1 else "https://kafka.apache.org/43/configuration/broker-configs/"

page = urllib.request.urlopen(URL, timeout=60).read().decode("utf-8")
blocks = re.findall(r"(<a id=brokerconfigs_[^ >]+ href=[^>]*>.*?</table>)", page, re.S)
rows = []
for block in blocks:
    name = re.match(r"<a id=brokerconfigs_([^ >]+)", block).group(1)
    m = re.search(r"<th>Update Mode:</th><td>(.*?)</td>", block, re.S)
    if not m:
        sys.exit("no Update Mode for %s, the page layout may have changed" % name)
    rows.append((name, html.unescape(re.sub("<[^>]+>", "", m.group(1))).strip()))
if len(rows) < 100:
    sys.exit("only %d broker configs found at %s, refusing to write a partial table" % (len(rows), URL))
modes = {mode for _, mode in rows}
if not modes <= {"read-only", "per-broker", "cluster-wide"}:
    sys.exit("unexpected update modes %s" % sorted(modes))

print("# Broker config update modes, generated by bench/tools/broker_update_modes.py")
print("# Source: %s" % URL)
print("# Fetched: %s" % datetime.date.today().isoformat())
print("# Columns: config name, update mode (read-only, per-broker or cluster-wide)")
for name, mode in sorted(rows):
    print("%s\t%s" % (name, mode))
